export function iconSvg(name, size = 16) {
  const body = PATHS[name] || PATHS.info;
  return `<svg class="icon" xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

/** Replace every <i data-icon="name"> placeholder under root with its SVG. */
export function renderIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    const size = Number(el.dataset.size) || 16;
    const wrapper = document.createElement('span');
    wrapper.innerHTML = iconSvg(el.dataset.icon, size);
    const svg = wrapper.firstElementChild;
    if (el.id) svg.id = el.id;
    if (el.className) svg.classList.add(...el.classList);
    el.replaceWith(svg);
  });
}

export function setIcon(svgEl, name) {
  if (!svgEl) return;
  svgEl.innerHTML = PATHS[name] || PATHS.info;
}
